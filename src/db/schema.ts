export const SCHEMA_V1 = `
CREATE TABLE IF NOT EXISTS crops (
  id INTEGER PRIMARY KEY AUTOINCREMENT,
  name TEXT NOT NULL,
  emoji TEXT NOT NULL,
  createdAt TEXT NOT NULL
);
CREATE TABLE IF NOT EXISTS input_purchases (
  id INTEGER PRIMARY KEY AUTOINCREMENT,
  cropId INTEGER NOT NULL REFERENCES crops(id) ON DELETE CASCADE,
  item TEXT NOT NULL,
  quantity REAL NOT NULL DEFAULT 0,
  unit TEXT NOT NULL DEFAULT '',
  cost INTEGER NOT NULL DEFAULT 0,
  datePurchased TEXT NOT NULL,
  note TEXT NOT NULL DEFAULT ''
);
CREATE TABLE IF NOT EXISTS activities (
  id INTEGER PRIMARY KEY AUTOINCREMENT,
  cropId INTEGER NOT NULL REFERENCES crops(id) ON DELETE CASCADE,
  type TEXT NOT NULL,
  description TEXT NOT NULL DEFAULT '',
  cost INTEGER NOT NULL DEFAULT 0,
  date TEXT NOT NULL,
  note TEXT NOT NULL DEFAULT ''
);
CREATE TABLE IF NOT EXISTS harvests (
  id INTEGER PRIMARY KEY AUTOINCREMENT,
  cropId INTEGER NOT NULL REFERENCES crops(id) ON DELETE CASCADE,
  date TEXT NOT NULL,
  quantity REAL NOT NULL DEFAULT 0,
  unit TEXT NOT NULL,
  note TEXT NOT NULL DEFAULT ''
);
CREATE TABLE IF NOT EXISTS sales (
  id INTEGER PRIMARY KEY AUTOINCREMENT,
  cropId INTEGER NOT NULL REFERENCES crops(id) ON DELETE CASCADE,
  date TEXT NOT NULL,
  quantity REAL NOT NULL DEFAULT 0,
  unit TEXT NOT NULL,
  pricePerUnit INTEGER NOT NULL DEFAULT 0,
  total INTEGER NOT NULL DEFAULT 0,
  buyer TEXT NOT NULL DEFAULT '',
  note TEXT NOT NULL DEFAULT ''
);
CREATE TABLE IF NOT EXISTS accounts (
  id INTEGER PRIMARY KEY AUTOINCREMENT,
  name TEXT NOT NULL,
  targetPercent INTEGER NOT NULL,
  sortOrder INTEGER NOT NULL
);
CREATE TABLE IF NOT EXISTS allocations (
  id INTEGER PRIMARY KEY AUTOINCREMENT,
  accountId INTEGER NOT NULL REFERENCES accounts(id) ON DELETE CASCADE,
  amount INTEGER NOT NULL,
  date TEXT NOT NULL,
  saleId INTEGER REFERENCES sales(id) ON DELETE SET NULL,
  note TEXT NOT NULL DEFAULT ''
);
CREATE INDEX IF NOT EXISTS idx_inputs_crop ON input_purchases(cropId);
CREATE INDEX IF NOT EXISTS idx_activities_crop ON activities(cropId);
CREATE INDEX IF NOT EXISTS idx_harvests_crop ON harvests(cropId);
CREATE INDEX IF NOT EXISTS idx_sales_crop ON sales(cropId);
CREATE INDEX IF NOT EXISTS idx_alloc_account ON allocations(accountId);
CREATE INDEX IF NOT EXISTS idx_alloc_sale ON allocations(saleId);
`;
